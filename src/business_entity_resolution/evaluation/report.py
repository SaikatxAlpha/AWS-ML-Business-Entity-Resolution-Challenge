"""Render reports/experiment_report.md from logged results only (no hand-typed numbers).

Sources: experiments/results.csv, experiments/runs/*.json, cache/features/dev_train_results.json,
models/*.json, output/run_report.json.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

from ..config import EXPERIMENTS_DIR, MODELS_DIR, OUTPUT_DIR, REPORTS_DIR, cache_path


def _f(v, nd=4):
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return "–" if v in (None, "") else str(v)


def _table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(x).replace("|", "\\|") for x in r) + " |" for r in rows]
    return "\n".join(out)


def _rows(stage_prefix: str):
    with open(EXPERIMENTS_DIR / "results.csv", newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f) if r.get("stage", "").startswith(stage_prefix)]


def _json(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def render() -> str:
    parts = ["# Experiment report\n",
             "_Generated by `python -m business_entity_resolution.evaluation.report` from `experiments/results.csv` "
             "and run artefacts. Validation = fold-0 validation entities (never used for fitting or tuning); "
             "every threshold/policy was tuned on training-fold entities._\n"]
    tr = _json(cache_path("features", "x").parent / "dev_train_results.json")

    parts.append("## 1. Baselines (Stage 4)\n")
    rows = [[r["experiment_id"], r["model"], _f(r["threshold"], 2), _f(r["candidate_recall"]), _f(r["precision"]),
             _f(r["recall"]), _f(r["f05"]), _f(r["singleton_accuracy"])] for r in _rows("floor") + _rows("4-baseline")]
    parts.append(_table(rows, ["experiment", "rule", "threshold", "cand. recall", "precision", "recall", "F0.5", "singleton acc."]))

    parts.append("\n\n## 2. Candidate generation (Stage 5–6)\n")
    rows = [[r["experiment_id"], r["hyperparameters"], _f(r["candidate_recall"]), _f(r["average_candidates"], 1),
             _f(r["runtime_s"], 0), r["notes"][:90]] for r in _rows("5-blocking")]
    parts.append(_table(rows, ["block / union", "K", "candidate recall", "avg candidates / S1", "runtime s", "notes"]))

    parts.append("\n\n## 3. Pairwise models (Stage 8, 12)\n")
    rows = [[r["experiment_id"], r["model"], _f(r["threshold"], 2), _f(r["precision"]), _f(r["recall"]), _f(r["f05"]),
             _f(r["singleton_accuracy"]), _f(r["runtime_s"], 0), r["notes"][:80]] for r in _rows("8/12-model")]
    parts.append(_table(rows, ["experiment", "model", "threshold", "precision", "recall", "F0.5", "singleton acc.", "train s", "notes"]))
    if tr:
        cb = tr.get("class_balance", {})
        parts.append(f"\n\nTraining pairs: {tr['n_pairs']}; positive rate {cb.get('model_pos_rate', 0):.4f} "
                     f"({cb.get('neg_per_pos', 0):.1f} negatives per positive — all negatives are hard negatives "
                     f"from the blocked candidate set). Selected model: **{tr.get('selected_model')}** (by calib F0.5).\n")

    if tr and "calibration" in tr:
        parts.append("\n## 4. Calibration (Stage 11)\n")
        rows = [[k, _f(v["ece_calib_half_b"])] for k, v in tr["calibration"].items()]
        parts.append(_table(rows, ["probabilities", "ECE (fit on calib half A, measured on half B)"]))
        rel = tr.get("reliability_raw_val") or []
        parts.append("\n\nReliability of raw probabilities on validation pairs:\n\n" + _table(
            [[r["bin"], r["n"], _f(r["mean_p"]), _f(r["frac_pos"])] for r in rel], ["bin", "pairs", "mean p", "fraction positive"]))

    parts.append("\n\n## 5. Decision policies — thresholds, abstention, cardinality, singleton protection (Stages 9–14)\n")
    rows = [[r["experiment_id"], r["threshold"][:80], _f(r["precision"]), _f(r["recall"]), _f(r["f05"]),
             _f(r["singleton_accuracy"]), r["notes"][:60]] for r in _rows("11-14-decision")]
    parts.append(_table(rows, ["experiment", "policy", "precision", "recall", "F0.5", "singleton acc.", "notes"]))
    if tr:
        parts.append(f"\n\nSelected policy (by calib F0.5): **{tr.get('selected_policy')}**.\n")
        sel = tr["policies"].get(tr.get("selected_policy"), {})
        grp = sel.get("val", {}).get("f05_by_group")
        if grp:
            parts.append("\nValidation F0.5 by country × true-cardinality bucket (selected policy):\n\n" +
                         _table([[k, _f(v)] for k, v in sorted(grp.items())], ["group", "F0.5"]))

    parts.append("\n\n## 6. Ablation (Stage 18) — cumulative feature groups, XGBoost, global threshold\n")
    rows = [[r["experiment_id"], r["hyperparameters"], _f(r["precision"]), _f(r["recall"]), _f(r["f05"]),
             _f(r["singleton_accuracy"])] for r in _rows("18-ablation")]
    parts.append(_table(rows, ["step", "features", "precision", "recall", "F0.5", "singleton acc."]))

    if tr and tr.get("feature_importance_gain"):
        top = list(tr["feature_importance_gain"].items())[:25]
        parts.append("\n\n## 7. Feature importance (gain, selected model, top 25)\n\n" +
                     _table([[k, f"{v:,.1f}"] for k, v in top], ["feature", "gain"]))

    rep = _json(OUTPUT_DIR / "run_report.json")
    spec = _json(MODELS_DIR / "matcher_spec.json")
    if rep:
        parts.append("\n\n## 8. Test inference (unlabelled — no score available)\n")
        parts.append(_table([[k, json.dumps(v) if isinstance(v, dict) else v] for k, v in rep.items()
                             if k not in ("validator_output", "files")], ["item", "value"]))
        if "validator_output" in rep:
            parts.append("\n\nOfficial validator output:\n\n```\n" + rep["validator_output"].strip() + "\n```\n")
    if spec:
        parts.append("\n\nFinal spec (`models/matcher_spec.json`): model=" + str(spec.get("model")) + ", policy=" +
                     json.dumps(spec.get("policy")) + ", calibration=" + str(spec.get("calibration")) + ", blocks=" +
                     json.dumps(spec.get("blocks")) + "\n")
    return "\n".join(parts) + "\n"


def write() -> Path:
    REPORTS_DIR.mkdir(exist_ok=True)
    p = REPORTS_DIR / "experiment_report.md"
    p.write_text(render(), encoding="utf-8")
    return p


if __name__ == "__main__":
    print(write())
